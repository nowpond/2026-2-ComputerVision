"""## 4. KNN 직접 구현

- L1 거리: 픽셀별 절댓값 차이의 합
- L2 거리: 픽셀별 차이 제곱의 합의 제곱근. CPU 경로는 **제곱 L2**, GPU 경로는 L2를 계산합니다. 제곱근은 거리의 순서를 바꾸지 않으므로 가장 가까운 이웃은 같습니다.
- 같은 거리 행렬에서 여러 `k` 값을 평가합니다. 투표가 동률이면 동률인 클래스 중 가장 가까운 이웃의 클래스를 선택합니다.

거리 행렬은 쿼리 배치 단위로 만듭니다. GPU가 있으면 PyTorch의 `cdist`로 거리 계산을 가속하고, 학습 데이터를 작은 블록으로 나누어 가장 가까운 이웃만 유지합니다. 이웃 선택과 다수결은 직접 구현합니다. GPU가 없으면 NumPy 방식으로 실행되지만 전체 데이터에서는 매우 느릴 수 있습니다.

"""

class KNNClassifier:
    def fit(self, X, y):
        self.X = np.asarray(X, dtype=np.float32)
        self.y = np.asarray(y, dtype=np.int64)
        if self.X.ndim != 2 or self.y.shape != (len(self.X),):
            raise ValueError("X는 2차원 배열, y는 길이가 같은 1차원 배열이어야 합니다.")
        self.train_sq_norm = np.sum(self.X * self.X, axis=1)
        self.l1_buffer = None
        return self

    def _distances(self, queries, metric):
        if metric == "L2":
            query_sq_norm = np.sum(queries * queries, axis=1, keepdims=True)
            distances = query_sq_norm + self.train_sq_norm[None, :] - 2.0 * (queries @ self.X.T)
            np.maximum(distances, 0.0, out=distances)
            return distances
        if metric == "L1":
            if self.l1_buffer is None:
                self.l1_buffer = np.empty_like(self.X)
            distances = np.empty((len(queries), len(self.X)), dtype=np.float32)
            for row, query in enumerate(queries):
                np.subtract(self.X, query, out=self.l1_buffer)
                np.abs(self.l1_buffer, out=self.l1_buffer)
                distances[row] = self.l1_buffer.sum(axis=1)
            return distances
        raise ValueError("metric은 'L1' 또는 'L2'여야 합니다.")

    def predict_many(self, X, k_values, metric, batch_size=32):
        queries = np.asarray(X, dtype=np.float32)
        k_values = tuple(sorted(set(int(k) for k in k_values)))
        if queries.ndim != 2 or queries.shape[1] != self.X.shape[1]:
            raise ValueError("입력 이미지의 특징 차원이 학습 데이터와 다릅니다.")
        if not k_values or k_values[0] < 1 or k_values[-1] > len(self.X):
            raise ValueError("k는 1 이상, 학습 이미지 수 이하여야 합니다.")
        results = {k: np.empty(len(queries), dtype=np.int64) for k in k_values}
        max_k = k_values[-1]
        n_classes = int(self.y.max()) + 1
        for start in range(0, len(queries), batch_size):
            end = min(start + batch_size, len(queries))
            distances = self._distances(queries[start:end], metric)
            nearest = np.argpartition(distances, kth=max_k - 1, axis=1)[:, :max_k]
            order = np.argsort(np.take_along_axis(distances, nearest, axis=1), axis=1)
            nearest = np.take_along_axis(nearest, order, axis=1)
            neighbor_labels = self.y[nearest]
            counts = np.zeros((end - start, n_classes), dtype=np.int32)
            previous_k = 0
            for k in k_values:
                new_labels = neighbor_labels[:, previous_k:k]
                rows = np.broadcast_to(np.arange(end - start)[:, None], new_labels.shape)
                np.add.at(counts, (rows, new_labels), 1)
                max_votes = counts.max(axis=1)
                tied_classes = counts == max_votes[:, None]
                tied_neighbors = np.take_along_axis(tied_classes, neighbor_labels[:, :k], axis=1)
                first_winner = tied_neighbors.argmax(axis=1)
                results[k][start:end] = neighbor_labels[np.arange(end - start), first_winner]
                previous_k = k
        return results


class GPUKNNClassifier:
    """GPU에서 거리 블록을 계산하고, 전체 거리 행렬 없이 top-k를 유지한다."""
    def fit(self, X, y):
        if torch is None or not torch.cuda.is_available():
            raise RuntimeError("GPU 런타임이 필요합니다.")
        self.X = torch.as_tensor(np.asarray(X, dtype=np.float32), device="cuda")
        self.y = np.asarray(y, dtype=np.int64)
        return self

    def predict_many(self, X, k_values, metric, batch_size=64):
        queries = np.asarray(X, dtype=np.float32)
        k_values = tuple(sorted(set(int(k) for k in k_values)))
        if queries.ndim != 2 or queries.shape[1] != self.X.shape[1]:
            raise ValueError("입력 이미지의 특징 차원이 학습 데이터와 다릅니다.")
        if not k_values or k_values[0] < 1 or k_values[-1] > len(self.X):
            raise ValueError("k는 1 이상, 학습 이미지 수 이하여야 합니다.")
        if metric not in ("L1", "L2"):
            raise ValueError("metric은 'L1' 또는 'L2'여야 합니다.")
        p = 1.0 if metric == "L1" else 2.0
        max_k = k_values[-1]
        n_classes = int(self.y.max()) + 1
        results = {k: np.empty(len(queries), dtype=np.int64) for k in k_values}
        for start in range(0, len(queries), batch_size):
            end = min(start + batch_size, len(queries))
            query_tensor = torch.as_tensor(queries[start:end], device="cuda")
            best_dist = torch.full((end - start, max_k), float("inf"), device="cuda")
            best_idx = torch.full((end - start, max_k), -1, dtype=torch.long, device="cuda")
            for train_start in range(0, len(self.X), TRAIN_BATCH_SIZE):
                train_end = min(train_start + TRAIN_BATCH_SIZE, len(self.X))
                block_dist = torch.cdist(query_tensor, self.X[train_start:train_end], p=p)
                candidate_dist, candidate_idx = torch.topk(
                    block_dist, min(max_k, train_end - train_start), dim=1, largest=False, sorted=True
                )
                candidate_idx += train_start
                combined_dist = torch.cat((best_dist, candidate_dist), dim=1)
                combined_idx = torch.cat((best_idx, candidate_idx), dim=1)
                best_dist, selected = torch.topk(combined_dist, max_k, dim=1, largest=False, sorted=True)
                best_idx = torch.gather(combined_idx, 1, selected)
            neighbor_labels = self.y[best_idx.cpu().numpy()]
            counts = np.zeros((end - start, n_classes), dtype=np.int32)
            previous_k = 0
            for k in k_values:
                new_labels = neighbor_labels[:, previous_k:k]
                rows = np.broadcast_to(np.arange(end - start)[:, None], new_labels.shape)
                np.add.at(counts, (rows, new_labels), 1)
                max_votes = counts.max(axis=1)
                tied_classes = counts == max_votes[:, None]
                tied_neighbors = np.take_along_axis(tied_classes, neighbor_labels[:, :k], axis=1)
                first_winner = tied_neighbors.argmax(axis=1)
                results[k][start:end] = neighbor_labels[np.arange(end - start), first_winner]
                previous_k = k
        return results

