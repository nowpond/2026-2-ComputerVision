def stratified_sample_indices(labels, n_samples, seed):
    classes = np.unique(labels)
    if n_samples % len(classes):
        raise ValueError("표본 수는 클래스 수의 배수여야 합니다.")
    per_class = n_samples // len(classes)
    rng = np.random.default_rng(seed)
    chosen = []
    for label in classes:
        pool = np.flatnonzero(labels == label)
        if len(pool) < per_class:
            raise ValueError("요청한 표본 수가 클래스의 데이터 수보다 많습니다.")
        chosen.append(rng.choice(pool, size=per_class, replace=False))
    return rng.permutation(np.concatenate(chosen))

