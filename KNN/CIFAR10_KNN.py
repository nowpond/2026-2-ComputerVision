"""## 6. 4가지 지표와 5-fold 교차검증

정밀도·재현율·F1은 10개 클래스별 값을 먼저 계산한 뒤 단순 평균한 **macro 평균**을 사용합니다. 클래스별 점수 계산에서 분모가 0이면 해당 값을 0으로 둡니다. 각 fold의 검증 이미지는 그 fold의 학습 이미지에 포함되지 않습니다.

"""

def classification_metrics(y_true, y_pred, n_classes=10):
    matrix = np.zeros((n_classes, n_classes), dtype=np.int64)
    np.add.at(matrix, (y_true, y_pred), 1)
    tp = np.diag(matrix)
    precision = np.divide(tp, matrix.sum(axis=0), out=np.zeros(n_classes, dtype=float), where=matrix.sum(axis=0) != 0)
    recall = np.divide(tp, matrix.sum(axis=1), out=np.zeros(n_classes, dtype=float), where=matrix.sum(axis=1) != 0)
    f1 = np.divide(2 * precision * recall, precision + recall,
                   out=np.zeros(n_classes, dtype=float), where=precision + recall != 0)
    summary = {
        "accuracy": float(tp.sum() / matrix.sum()),
        "precision_macro": float(precision.mean()),
        "recall_macro": float(recall.mean()),
        "f1_macro": float(f1.mean()),
    }
    per_class = pd.DataFrame({"class": class_names[:n_classes], "precision": precision, "recall": recall,
                              "f1": f1, "support": matrix.sum(axis=1)})
    return summary, per_class, matrix

def stratified_folds(labels, n_folds, seed):
    rng = np.random.default_rng(seed)
    class_chunks = {}
    for label in np.unique(labels):
        indices = np.flatnonzero(labels == label)
        class_chunks[label] = np.array_split(rng.permutation(indices), n_folds)
    for fold in range(n_folds):
        validation = np.concatenate([class_chunks[label][fold] for label in class_chunks])
        training_mask = np.ones(len(labels), dtype=bool)
        training_mask[validation] = False
        yield np.flatnonzero(training_mask), validation

assert classification_metrics(np.array([0, 0, 1, 1]), np.array([0, 1, 1, 1]), 2)[0]["accuracy"] == 0.75

folds = list(stratified_folds(y_train, N_FOLDS, SEED))
assert len(folds) == 5 and len(np.unique(np.concatenate([v for _, v in folds]))) == len(y_train)
cv_rows = []
started = time.perf_counter()
for metric in DISTANCE_METRICS:
    for fold_number, (fit_idx, val_idx) in enumerate(folds, start=1):
        model = MODEL_CLASS().fit(X_train[fit_idx], y_train[fit_idx])
        predictions = model.predict_many(X_train[val_idx], K_VALUES, metric, QUERY_BATCH_SIZE)
        for k in K_VALUES:
            scores, _, _ = classification_metrics(y_train[val_idx], predictions[k])
            cv_rows.append({"metric": metric, "k": k, "fold": fold_number, **scores})
        print(f"{metric}, fold {fold_number}/{N_FOLDS} 완료 ({time.perf_counter() - started:.1f}초)")
        del model
        if USE_GPU:
            torch.cuda.empty_cache()

cv_results = pd.DataFrame(cv_rows)
score_columns = ["accuracy", "precision_macro", "recall_macro", "f1_macro"]
cv_summary = cv_results.groupby(["metric", "k"], as_index=False)[score_columns].agg(["mean", "std"])
cv_summary.columns = ["metric", "k"] + [f"{score}_{stat}" for score in score_columns for stat in ("mean", "std")]
